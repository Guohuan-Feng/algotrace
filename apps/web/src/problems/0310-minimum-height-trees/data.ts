  "from typing import List",
  "from collections import deque",
  "",
  "class Solution:",
  "    def findMinHeightTrees(self, n: int, edges: List[List[int]]) -> List[int]:",
  "",
  "        if n == 1:",
  "            return [0]",
  "",
  "        graph = [[] for _ in range(n)]",
  "",
  "        degree = [0] * n",
