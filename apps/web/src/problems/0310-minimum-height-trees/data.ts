  "                queue.append(i)",
  "",
  "        remaining = n",
  "",
  "        # 一层一层删除叶子",
  "        # 最后只剩 1 或 2 个节点，就是树的中心",
  "        while remaining > 2:",
  "",
  "            size = len(queue)",
  "",
  "            # 删除这一层的所有叶子",
  "            remaining -= size",
  "",
  "            for _ in range(size):",
  "                leaf = queue.popleft()",
  "",
  "                for nei in graph[leaf]:",
  "                    degree[nei] -= 1",
  "",
  "                    if degree[nei] == 1:",
  "                        queue.append(nei)",
  "",
  "        return list(queue)",
